"""Builds the sample take's narration (assets/sample-voice.mp3) and its mic
levels (src/sample-levels.js) from the phrases in src/sample.js, using the
Flite speech synthesiser (scripts/tts.py). Each line is fitted inside its
phrase window, so the narration, the edits and the captions line up.

Run from the repository root:  python3 scripts/sample-voice.py
"""
import json, os, re, subprocess, tempfile, wave
import numpy as np

SR = 24000
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, 'src/sample.js')).read()
duration = float(re.search(r'SAMPLE_DURATION = ([\d.]+)', src).group(1))
phrases = [(m.group(1) or m.group(2), float(m.group(3)), float(m.group(4)))
           for m in re.finditer(r"\{ text: (?:'([^']*)'|\"([^\"]*)\"), start: ([\d.]+), end: ([\d.]+) \}", src)]
tmp = tempfile.mkdtemp()

def speak(text):
    path = os.path.join(tmp, 'p.wav')
    subprocess.run(['python3', os.path.join(ROOT, 'scripts/tts.py'), text.replace(':', ','), path], check=True, capture_output=True)
    with wave.open(path) as w:
        x = np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(np.float32) / 32768
        rate = w.getframerate()
    x = np.interp(np.arange(0, len(x) * SR / rate) * rate / SR, np.arange(len(x)), x)
    env = np.convolve(np.abs(x), np.ones(240) / 240, 'same')
    on = np.where(env > 0.01)[0]
    return x[on[0]:on[-1]]

track = np.zeros(int(duration * SR), np.float32)
for text, start, end in phrases:
    x = speak(text)
    room = end - 0.35 - start
    if len(x) / SR > room:  # too long for its window: speed it up a little
        path = os.path.join(tmp, 'in.wav'); out = os.path.join(tmp, 'out.wav')
        with wave.open(path, 'wb') as w:
            w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes((x * 32767).astype(np.int16).tobytes())
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', path, '-filter:a', f'atempo={len(x) / SR / room:.3f}', out], check=True)
        with wave.open(out) as w:
            x = np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(np.float32) / 32768
    i = int(start * SR)
    track[i:i + len(x)] += x[: len(track) - i] * 0.85
track += np.random.default_rng(7).normal(0, 0.0015, len(track)).astype(np.float32)  # a little room tone

wav = os.path.join(tmp, 'voice.wav')
with wave.open(wav, 'wb') as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes((np.clip(track, -1, 1) * 32767).astype(np.int16).tobytes())
subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', wav, '-ac', '1', '-ar', '24000', '-b:a', '48k', os.path.join(ROOT, 'assets/sample-voice.mp3')], check=True)

# Mic levels, as the recorder measures them: RMS every 50 ms.
dt, n = 0.05, int(duration / 0.05)
levels = [float(np.sqrt(np.mean(track[int(k * dt * SR):int((k + 1) * dt * SR)] ** 2))) * 2.2 for k in range(n)]
with open(os.path.join(ROOT, 'src/sample-levels.js'), 'w') as f:
    f.write('// Generated by scripts/sample-voice.py: mic levels of assets/sample-voice.mp3, every 50 ms.\n')
    f.write('export const SAMPLE_LEVELS = ' + json.dumps([round(v, 4) for v in levels]) + ';\n')
print(len(phrases), 'phrases;', os.path.getsize(os.path.join(ROOT, 'assets/sample-voice.mp3')) // 1024, 'KB;', 'peak level', round(max(levels), 3))
